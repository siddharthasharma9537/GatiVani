String tr(String lang, String key) =>
    _kStrings[lang]?[key] ?? _kStrings['en']?[key] ?? key;

/// "5 stories" / "5 కథనాలు" / "1 story".
String storyCount(int n, String lang) {
  final word = tr(lang, n == 1 ? 'story_one' : 'story_many');
  return '$n $word';
}

